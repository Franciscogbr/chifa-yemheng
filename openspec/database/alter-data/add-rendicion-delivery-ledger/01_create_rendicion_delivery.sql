CREATE TABLE IF NOT EXISTS public.rendicion_delivery (
  id_rendicion integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empleado integer NOT NULL REFERENCES public.empleado(id_empleado),
  id_aperturacaja integer NOT NULL REFERENCES public.apertura_caja(id_aperturacaja),
  id_usuario integer NOT NULL REFERENCES public.usuario(id_usuario),
  id_movimientocaja integer REFERENCES public.movimiento_caja(id_movimientocaja),
  monto_esperado numeric(12,2) NOT NULL CHECK (monto_esperado >= 0),
  monto_entregado numeric(12,2) NOT NULL CHECK (monto_entregado >= 0),
  diferencia numeric(12,2) NOT NULL,
  estado character(1) NOT NULL CHECK (estado IN ('R', 'O', 'V')),
  observaciones character varying(500),
  id_usuariovalida integer REFERENCES public.usuario(id_usuario),
  f_validacion timestamp without time zone,
  usucre character varying(30) DEFAULT CURRENT_USER NOT NULL,
  pccre character varying(30),
  feccre timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
  usumod character varying(30),
  pcmod character varying(30),
  fecmod timestamp without time zone,
  CONSTRAINT ck_rendicion_diferencia CHECK (diferencia = monto_entregado - monto_esperado),
  CONSTRAINT ck_rendicion_validacion CHECK (
    (estado = 'V' AND id_usuariovalida IS NOT NULL AND f_validacion IS NOT NULL)
    OR (estado <> 'V' AND id_usuariovalida IS NULL AND f_validacion IS NULL)
  )
);

CREATE TABLE IF NOT EXISTS public.rendicion_delivery_detalle (
  id_rendicion integer NOT NULL REFERENCES public.rendicion_delivery(id_rendicion),
  id_pedidodelivery integer NOT NULL REFERENCES public.pedido_delivery(id_pedidodelivery),
  id_pedido integer NOT NULL REFERENCES public.pedido(id_pedido),
  total_esperado numeric(12,2) NOT NULL CHECK (total_esperado >= 0),
  PRIMARY KEY (id_rendicion, id_pedidodelivery),
  CONSTRAINT uq_rendicion_detalle_pedido UNIQUE (id_pedido),
  CONSTRAINT uq_rendicion_detalle_delivery UNIQUE (id_pedidodelivery)
);

CREATE INDEX IF NOT EXISTS ix_rendicion_delivery_fecha
  ON public.rendicion_delivery (feccre DESC);
CREATE INDEX IF NOT EXISTS ix_rendicion_delivery_repartidor_fecha
  ON public.rendicion_delivery (id_empleado, feccre DESC);
CREATE INDEX IF NOT EXISTS ix_rendicion_delivery_estado_fecha
  ON public.rendicion_delivery (estado, feccre DESC);

CREATE TABLE IF NOT EXISTS public.dispositivo_token (
  id_dispositivo_token integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_empleado integer NOT NULL REFERENCES public.empleado(id_empleado),
  token text NOT NULL UNIQUE,
  plataforma character varying(10) NOT NULL CHECK (plataforma IN ('web', 'android', 'ios')),
  activo boolean NOT NULL DEFAULT true,
  usucre character varying(30) DEFAULT CURRENT_USER NOT NULL,
  feccre timestamp without time zone DEFAULT CURRENT_TIMESTAMP NOT NULL,
  usumod character varying(30),
  fecmod timestamp without time zone
);

CREATE INDEX IF NOT EXISTS ix_dispositivo_token_empleado_activo
  ON public.dispositivo_token (id_empleado)
  WHERE activo = true;

ALTER TABLE public.rendicion_delivery ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rendicion_delivery_detalle ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dispositivo_token ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON public.rendicion_delivery, public.rendicion_delivery_detalle
  FROM PUBLIC, anon, authenticated;
REVOKE ALL ON public.dispositivo_token FROM PUBLIC, anon, authenticated;
GRANT SELECT, INSERT, UPDATE ON public.rendicion_delivery, public.rendicion_delivery_detalle
  TO service_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.dispositivo_token TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.rendicion_delivery_id_rendicion_seq TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.dispositivo_token_id_dispositivo_token_seq TO service_role;

CREATE OR REPLACE FUNCTION public.fn_registrar_rendicion_delivery(
  p_id_empleado integer,
  p_pedido_ids integer[],
  p_monto_entregado numeric,
  p_observaciones character varying,
  p_id_usuario integer,
  p_logeo character varying,
  p_pc character varying
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_ids_distintos integer;
  v_pedidos_validos integer;
  v_total_esperado numeric(12,2);
  v_diferencia numeric(12,2);
  v_estado character(1);
  v_id_apertura integer;
  v_id_concepto integer;
  v_id_metodo integer;
  v_id_rendicion integer;
  v_id_movimiento integer;
BEGIN
  IF p_id_empleado IS NULL OR p_id_empleado <= 0
    OR p_id_usuario IS NULL OR p_id_usuario <= 0
    OR p_logeo IS NULL OR btrim(p_logeo) = ''
    OR p_pedido_ids IS NULL OR cardinality(p_pedido_ids) = 0
    OR cardinality(p_pedido_ids) > 100
    OR array_position(p_pedido_ids, NULL::integer) IS NOT NULL
    OR p_monto_entregado IS NULL OR p_monto_entregado < 0
    OR p_monto_entregado <> round(p_monto_entregado, 2)
    OR length(coalesce(p_observaciones, '')) > 500 THEN
    RAISE EXCEPTION 'VALIDATION_ERROR';
  END IF;

  SELECT count(DISTINCT id_pedido)
    INTO v_ids_distintos
    FROM unnest(p_pedido_ids) AS pedidos(id_pedido);

  IF v_ids_distintos <> cardinality(p_pedido_ids) THEN
    RAISE EXCEPTION 'PEDIDO_DUPLICADO';
  END IF;

  PERFORM pd.id_pedidodelivery
    FROM public.pedido_delivery pd
    WHERE pd.id_pedido = ANY (p_pedido_ids)
      AND pd.id_empleado = p_id_empleado
      AND pd.situacion = 'E'
      AND pd.estado = 'A'
    FOR UPDATE;

  IF EXISTS (
    SELECT 1
      FROM public.rendicion_delivery_detalle d
      WHERE d.id_pedido = ANY (p_pedido_ids)
  ) OR EXISTS (
    SELECT 1
      FROM public.movimiento_caja mc
      WHERE mc.id_pedido = ANY (p_pedido_ids)
        AND mc.estado = 'A'
        AND mc.descripcion ILIKE 'Rendición delivery repartidor %'
  ) THEN
    RAISE EXCEPTION 'PEDIDO_YA_RENDIDO';
  END IF;

  WITH pedidos_validos AS (
    SELECT pd.id_pedidodelivery,
           pd.id_pedido,
           round(sum(pg.monto) + pd.costo_envio, 2) AS total_esperado
      FROM public.pedido_delivery pd
      JOIN public.pedido p ON p.id_pedido = pd.id_pedido
      JOIN public.venta v ON v.id_pedido = p.id_pedido AND v.anulada = 'N' AND v.estado = 'A'
      JOIN public.pago_venta pg ON pg.id_venta = v.id_venta AND pg.estado = 'A'
      JOIN public.metodo_pago mp ON mp.id_metodopago = pg.id_metodopago
        AND mp.afecta_efectivo = 'S' AND mp.estado = 'A'
      WHERE pd.id_pedido = ANY (p_pedido_ids)
        AND pd.id_empleado = p_id_empleado
        AND pd.situacion = 'E'
        AND pd.estado = 'A'
      GROUP BY pd.id_pedidodelivery, pd.id_pedido, pd.costo_envio
  )
  SELECT count(*), coalesce(sum(total_esperado), 0)
    INTO v_pedidos_validos, v_total_esperado
    FROM pedidos_validos;

  IF v_pedidos_validos <> cardinality(p_pedido_ids) THEN
    RAISE EXCEPTION 'PEDIDO_NO_VALIDO';
  END IF;

  v_diferencia := p_monto_entregado - v_total_esperado;
  IF v_diferencia <> 0 AND coalesce(btrim(p_observaciones), '') = '' THEN
    RAISE EXCEPTION 'OBSERVACION_REQUERIDA';
  END IF;
  v_estado := CASE WHEN v_diferencia = 0 THEN 'R' ELSE 'O' END;

  SELECT ac.id_aperturacaja
    INTO v_id_apertura
    FROM public.apertura_caja ac
    WHERE ac.situacion = 'A' AND ac.estado = 'A'
    ORDER BY ac.feccre DESC
    LIMIT 1
    FOR UPDATE;

  IF v_id_apertura IS NULL THEN
    RAISE EXCEPTION 'CAJA_NO_ABIERTA';
  END IF;

  SELECT cc.id_concepto
    INTO v_id_concepto
    FROM public.concepto_caja cc
    WHERE upper(btrim(cc.n_concepto)) = 'VENTA AL CONTADO'
      AND cc.estado = 'A'
    ORDER BY cc.id_concepto
    LIMIT 1;

  SELECT mp.id_metodopago
    INTO v_id_metodo
    FROM public.metodo_pago mp
    WHERE mp.afecta_efectivo = 'S' AND mp.estado = 'A'
    ORDER BY mp.id_metodopago
    LIMIT 1;

  IF v_id_concepto IS NULL OR v_id_metodo IS NULL THEN
    RAISE EXCEPTION 'CATALOGO_CAJA_NO_DISPONIBLE';
  END IF;

  INSERT INTO public.rendicion_delivery (
    id_empleado, id_aperturacaja, id_usuario, monto_esperado,
    monto_entregado, diferencia, estado, observaciones, usucre, pccre
  )
  VALUES (
    p_id_empleado, v_id_apertura, p_id_usuario, v_total_esperado,
    p_monto_entregado, v_diferencia, v_estado, nullif(btrim(p_observaciones), ''),
    left(p_logeo, 30), left(nullif(p_pc, ''), 30)
  )
  RETURNING id_rendicion INTO v_id_rendicion;

  INSERT INTO public.rendicion_delivery_detalle (
    id_rendicion, id_pedidodelivery, id_pedido, total_esperado
  )
  SELECT v_id_rendicion, pd.id_pedidodelivery, pd.id_pedido,
         round(sum(pg.monto) + pd.costo_envio, 2)
    FROM public.pedido_delivery pd
    JOIN public.pedido p ON p.id_pedido = pd.id_pedido
    JOIN public.venta v ON v.id_pedido = p.id_pedido AND v.anulada = 'N' AND v.estado = 'A'
    JOIN public.pago_venta pg ON pg.id_venta = v.id_venta AND pg.estado = 'A'
    JOIN public.metodo_pago mp ON mp.id_metodopago = pg.id_metodopago
      AND mp.afecta_efectivo = 'S' AND mp.estado = 'A'
    WHERE pd.id_pedido = ANY (p_pedido_ids)
      AND pd.id_empleado = p_id_empleado
      AND pd.situacion = 'E'
      AND pd.estado = 'A'
    GROUP BY pd.id_pedidodelivery, pd.id_pedido, pd.costo_envio;

  IF p_monto_entregado > 0 THEN
    SELECT mov.id_movimientocaja
      INTO v_id_movimiento
      FROM public.fn_registrar_movimiento_caja(
        v_id_apertura, v_id_concepto, v_id_metodo, p_id_usuario,
        p_monto_entregado, 'Rendición delivery #' || v_id_rendicion,
        NULL, NULL, NULL
      ) AS mov;

    IF v_id_movimiento IS NULL THEN
      RAISE EXCEPTION 'MOVIMIENTO_CAJA_FAIL';
    END IF;

    UPDATE public.rendicion_delivery
      SET id_movimientocaja = v_id_movimiento
      WHERE id_rendicion = v_id_rendicion;
  END IF;

  RETURN jsonb_build_object(
    'id', v_id_rendicion,
    'estado', CASE WHEN v_estado = 'R' THEN 'Rendido' ELSE 'Observado' END,
    'diferencia', v_diferencia,
    'totalEsperado', v_total_esperado
  );
END;
$$;

REVOKE ALL ON FUNCTION public.fn_registrar_rendicion_delivery(integer, integer[], numeric, character varying, integer, character varying, character varying)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.fn_registrar_rendicion_delivery(integer, integer[], numeric, character varying, integer, character varying, character varying)
  TO service_role;
