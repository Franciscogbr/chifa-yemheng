   - USP_* TRAN/RAISERROR/SCOPE_IDENTITY -> PROCEDURE plpgsql + CALL
   - Triggers inserted/deleted -> NEW/OLD por fila
   - Vistas: + -> ||, ISNULL -> COALESCE, DATEDIFF -> EXTRACT(EPOCH...),
             CONVERT(date) -> ::DATE, sin TOP 100 PERCENT
   ================================================================================== */

