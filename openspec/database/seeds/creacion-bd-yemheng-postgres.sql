   ----------------------------------------------------------------------------------
   Equivalencias aplicadas:
   - int IDENTITY(1,1)      -> INTEGER GENERATED BY DEFAULT AS IDENTITY
   - bigint IDENTITY(1,1)   -> BIGINT GENERATED BY DEFAULT AS IDENTITY
